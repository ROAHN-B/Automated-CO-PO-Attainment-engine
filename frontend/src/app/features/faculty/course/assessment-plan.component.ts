import { Component, DestroyRef, computed, inject, signal } from '@angular/core';
import { takeUntilDestroyed } from '@angular/core/rxjs-interop';
import { FormsModule } from '@angular/forms';
import { RouterLink } from '@angular/router';
import { ActivityType, AssessmentPlan, PlannedAssessment } from '../../../core/models/faculty-workspace.model';
import { FacultyWorkspaceService, WorkspaceError } from '../../../core/services/faculty-workspace.service';
import { BodyPortalDirective } from '../../../shared/ui/body-portal.directive';
import { IconComponent } from '../../../shared/ui/icon.component';
import { STEP_PURPOSE, categoryLabel } from '../lifecycle';
import { CourseContext } from './course-context';

const ACTIVITY_LABELS: Record<ActivityType, string> = {
  ASSIGNMENT: 'Assignment', CRITICAL_PROBLEM: 'Critical problem', SEMINAR_PRESENTATION: 'Seminar presentation',
  CASE_STUDY: 'Case study', MINI_PROJECT: 'Mini project', REAL_LIFE_PROBLEM: 'Real-life problem',
};

/** The fields the faculty may change (PLAN-2). */
interface Row { assessmentId: string; plannedDate: string; activityType: ActivityType | '' }

/**
 * Setup step 2, Assessment plan (API_CONTRACT §8): generated by the server from
 * the coordinator's load distribution. The faculty orders the assessments (the
 * order of the assessment cycles), adds dates and activity types, then
 * finalizes (PLAN-3), which opens the CAM.
 */
@Component({
  selector: 'app-assessment-plan',
  standalone: true,
  imports: [FormsModule, RouterLink, IconComponent, BodyPortalDirective],
  template: `
    <div class="space-y-6 animate-enter">
      <header>
        <p class="page-kicker">Course setup</p>
        <h2 class="mt-1.5 font-serif text-[32px] font-light leading-tight text-ink">Assessment plan</h2>
        <p class="mt-2 max-w-2xl text-[15px] text-ink-soft">{{ purpose }}</p>
      </header>

      @if (stepState()?.status === 'LOCKED') {
        <div class="alert alert-info">
          <app-icon name="lock" class="mt-0.5 h-4 w-4" />
          <div><p class="font-semibold text-ink">This step is locked</p><p class="mt-0.5">{{ stepState()?.lockedReason }}</p></div>
        </div>
      }

      @if (loading() && !plan()) {
        <div class="skeleton h-80" aria-busy="true" aria-label="Loading the plan"></div>
      } @else if (loadError()) {
        <div class="alert alert-error" role="alert">
          <app-icon name="alert" class="mt-0.5 h-4 w-4" />
          <div class="flex-1"><p class="font-semibold">Couldn’t load the plan</p><p class="mt-0.5">{{ loadError() }}</p></div>
          <button type="button" class="btn btn-outline btn-sm" (click)="load()">Try again</button>
        </div>
      } @else if (plan()) { @let p = plan()!;
        <!-- The coordinator's totals -->
        <section class="panel" aria-label="Marks by component">
          <div class="panel-grid" [style.grid-template-columns]="'repeat(' + p.examinationScheme.components.length + ', minmax(0, 1fr))'">
            @for (c of p.examinationScheme.components; track c.type) {
              <div class="panel-cell px-6 py-5">
                <p class="stat-label">{{ c.type === 'OE_POE' ? 'OE/POE' : c.type }}</p>
                <p class="stat-value">{{ c.maxMarks }}</p>
              </div>
            }
          </div>
        </section>

        @if (p.status === 'FINALIZED') {
          <div class="alert alert-info">
            <app-icon name="check" class="mt-0.5 h-4 w-4" [stroke]="2" />
            <p>The plan is finalized: its order is the order of your assessment cycles.</p>
          </div>
        } @else if (p.issues.length) {
          <div class="alert alert-warning" role="status">
            <app-icon name="alert" class="mt-0.5 h-4 w-4" />
            <div>
              <p class="font-semibold">Before you can finalize</p>
              <ul class="mt-1 list-disc pl-4">@for (i of p.issues; track $index) { <li>{{ i.message }}</li> }</ul>
            </div>
          </div>
        }

        <section class="card overflow-hidden" aria-label="Planned assessments">
          <div class="table-wrap">
            <table class="data-table">
              <thead>
                <tr>
                  <th class="th w-16">Order</th>
                  <th class="th">Assessment</th>
                  <th class="th text-right">Marks</th>
                  <th class="th">Activity type</th>
                  <th class="th">Planned date</th>
                </tr>
              </thead>
              <tbody>
                @for (a of ordered(); track a.assessmentId; let i = $index; let first = $first; let last = $last) { @let r = row(a.assessmentId);
                  <tr>
                    <td class="td">
                      <div class="flex items-center gap-1">
                        <span class="numeral w-6 text-[17px]">{{ i + 1 }}</span>
                        @if (editable()) {
                          <button type="button" class="btn btn-ghost btn-icon h-7 w-7" (click)="move(i, -1)" [disabled]="first || !!busy()" [attr.aria-label]="'Move ' + a.name + ' earlier'">
                            <app-icon name="chevronDown" class="h-4 w-4 rotate-180" />
                          </button>
                          <button type="button" class="btn btn-ghost btn-icon h-7 w-7" (click)="move(i, 1)" [disabled]="last || !!busy()" [attr.aria-label]="'Move ' + a.name + ' later'">
                            <app-icon name="chevronDown" class="h-4 w-4" />
                          </button>
                        }
                      </div>
                    </td>
                    <td class="td">
                      <p class="font-medium text-ink">{{ a.name }}</p>
                      <p class="text-[13px] text-ink-muted">{{ categoryLabel(a.category) }} · {{ a.phase }} phase</p>
                    </td>
                    <td class="td text-right tnum">{{ a.maxMarks }}</td>
                    <td class="td">
                      @if (a.category === 'ACTIVITY') {
                        <label class="sr-only" [for]="'ap-type-' + a.assessmentId">Type of {{ a.name }}</label>
                        <select [id]="'ap-type-' + a.assessmentId" class="field-select h-9 text-[13px]" [(ngModel)]="r.activityType" [disabled]="!editable() || !!busy()"
                                [class.field-invalid]="!r.activityType && p.status === 'DRAFT'">
                          <option value="">Choose…</option>
                          @for (t of activityTypes; track t) { <option [value]="t">{{ activityLabels[t] }}</option> }
                        </select>
                      } @else {
                        <span class="text-ink-faint">—</span>
                      }
                    </td>
                    <td class="td">
                      <label class="sr-only" [for]="'ap-date-' + a.assessmentId">Planned date of {{ a.name }}</label>
                      <input [id]="'ap-date-' + a.assessmentId" type="date" class="field-input h-9 w-40 text-[13px]" [(ngModel)]="r.plannedDate" [disabled]="!editable() || !!busy()" />
                    </td>
                  </tr>
                }
              </tbody>
            </table>
          </div>
        </section>
        <p class="text-xs text-ink-muted">Which assessments exist and their marks come from the coordinator’s syllabus. COs are linked later, in the CAM and the marksheets.</p>

        @if (error()) {
          <div class="alert alert-error" role="alert">
            <app-icon name="alert" class="mt-0.5 h-4 w-4" />
            <p class="flex-1">{{ error() }}</p>
            @if (conflict()) { <button type="button" class="btn btn-outline btn-sm" (click)="load()">Reload</button> }
          </div>
        }

        <div class="flex flex-wrap items-center justify-end gap-2">
          @if (p.status === 'FINALIZED') {
            <a class="btn btn-primary" routerLink="../cam">Next: Course articulation matrix <app-icon name="arrowRight" class="h-4 w-4" /></a>
          } @else if (editable()) {
            @if (saved() && !changed()) { <span class="mr-auto text-sm text-ink-soft" role="status">Saved.</span> }
            <button type="button" class="btn btn-outline" (click)="save()" [disabled]="!!busy() || !changed()">
              @if (busy() === 'save') { <span class="spinner"></span> Saving… } @else { Save }
            </button>
            <button type="button" class="btn btn-primary" (click)="confirming.set(true)" [disabled]="!!busy() || changed() || p.issues.length > 0"
                    [attr.title]="changed() ? 'Save your changes first' : null">Finalize plan</button>
          }
        </div>
      }
    </div>

    @if (confirming()) {
      <div class="modal-backdrop" appBodyPortal (click)="busy() || confirming.set(false)">
        <div class="modal max-w-md" role="dialog" aria-modal="true" aria-labelledby="ap-confirm-title" (click)="$event.stopPropagation()">
          <div class="p-6">
            <h3 id="ap-confirm-title" class="font-serif text-2xl font-light text-ink">Finalize the assessment plan?</h3>
            <p class="mt-3 text-sm leading-relaxed text-ink-soft">
              Its {{ plan()?.assessments?.length }} assessments become your assessment cycles, in this order, and the order can’t change afterwards.
              The course articulation matrix opens next.
            </p>
          </div>
          <div class="flex justify-end gap-2 border-t border-line px-6 py-4">
            <button type="button" class="btn btn-ghost" [disabled]="!!busy()" (click)="confirming.set(false)">Cancel</button>
            <button type="button" class="btn btn-primary" [disabled]="!!busy()" (click)="finalize()">
              @if (busy() === 'finalize') { <span class="spinner"></span> Finalizing… } @else { Finalize }
            </button>
          </div>
        </div>
      </div>
    }
  `,
})
export class AssessmentPlanComponent {
  readonly ctx = inject(CourseContext);
  private readonly api = inject(FacultyWorkspaceService);
  private readonly destroyRef = inject(DestroyRef);

  readonly purpose = STEP_PURPOSE.ASSESSMENT_PLAN;
  readonly activityTypes = Object.keys(ACTIVITY_LABELS) as ActivityType[];
  readonly activityLabels = ACTIVITY_LABELS;
  categoryLabel = categoryLabel;

  readonly plan = signal<AssessmentPlan | null>(null);
  readonly loading = signal(true);
  readonly loadError = signal<string | null>(null);
  readonly busy = signal<'save' | 'finalize' | null>(null);
  readonly error = signal<string | null>(null);
  readonly conflict = signal(false);
  readonly saved = signal(false);
  readonly confirming = signal(false);

  /** The editable copy: assessment IDs in the faculty's order, plus dates and activity types. */
  readonly order = signal<string[]>([]);
  rows: Record<string, Row> = {};

  readonly stepState = computed(() => this.ctx.offering()?.progress.setup.assessmentPlan ?? null);
  readonly editable = computed(() => this.plan()?.status === 'DRAFT' && this.stepState()?.status !== 'LOCKED');
  readonly ordered = computed<PlannedAssessment[]>(() => {
    const byId = new Map((this.plan()?.assessments ?? []).map(a => [a.assessmentId, a]));
    return this.order().map(id => byId.get(id)!).filter(Boolean);
  });

  constructor() {
    this.load();
  }

  load(): void {
    this.loading.set(true);
    this.loadError.set(null);
    this.error.set(null);
    this.conflict.set(false);
    this.api.assessmentPlan(this.ctx.offeringId()).pipe(takeUntilDestroyed(this.destroyRef)).subscribe({
      next: p => { this.setPlan(p); this.loading.set(false); },
      error: (e: WorkspaceError) => { this.loadError.set(e.message); this.loading.set(false); },
    });
  }

  row(id: string): Row {
    return this.rows[id];
  }

  move(i: number, step: -1 | 1): void {
    this.order.update(ids => {
      const next = [...ids];
      [next[i], next[i + step]] = [next[i + step], next[i]];
      return next;
    });
  }

  /** Whether the form differs from the server's plan. */
  changed(): boolean {
    const p = this.plan();
    if (!p) return false;
    const serverOrder = [...p.assessments].sort((a, b) => a.order - b.order).map(a => a.assessmentId);
    return this.order().join() !== serverOrder.join()
      || p.assessments.some(a => (a.plannedDate ?? '') !== this.rows[a.assessmentId].plannedDate
        || (a.activityType ?? '') !== this.rows[a.assessmentId].activityType);
  }

  save(): void {
    const p = this.plan();
    if (!p) return;
    this.busy.set('save');
    this.error.set(null);
    this.saved.set(false);
    this.api.saveAssessmentPlan(this.ctx.offeringId(), {
      version: p.version,
      assessments: this.order().map((id, i) => ({
        assessmentId: id, order: i + 1,
        plannedDate: this.rows[id].plannedDate || undefined,
        activityType: this.rows[id].activityType || undefined,
      })),
    }).subscribe({
      next: saved => { this.busy.set(null); this.saved.set(true); this.setPlan(saved); this.ctx.refresh(); },
      error: (e: WorkspaceError) => { this.busy.set(null); this.error.set(e.message); this.conflict.set(e.errorCode === 'VERSION_CONFLICT'); },
    });
  }

  finalize(): void {
    const p = this.plan();
    if (!p) return;
    this.busy.set('finalize');
    this.error.set(null);
    this.api.finalizeAssessmentPlan(this.ctx.offeringId(), p.version).subscribe({
      next: done => { this.busy.set(null); this.confirming.set(false); this.setPlan(done); this.ctx.refresh(); },
      error: (e: WorkspaceError) => { this.busy.set(null); this.confirming.set(false); this.error.set(e.message); },
    });
  }

  private setPlan(p: AssessmentPlan): void {
    this.plan.set(p);
    this.order.set([...p.assessments].sort((a, b) => a.order - b.order).map(a => a.assessmentId));
    this.rows = Object.fromEntries(p.assessments.map(a => [a.assessmentId, {
      assessmentId: a.assessmentId, plannedDate: a.plannedDate ?? '', activityType: a.activityType ?? '',
    }]));
  }
}
